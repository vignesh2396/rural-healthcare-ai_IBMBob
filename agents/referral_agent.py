"""
Agent 3: Referral Planning Agent
==================================
Purpose: Creates structured navigation referral plans, coordinates with
         facilities, and provides step-by-step action plans for patients.
         Explains what to bring, what to expect, and how to get there.

Responsibilities:
  - Generate navigation referral summaries
  - Provide actionable step-by-step patient guidance
  - Include government scheme eligibility hints
  - Specify documents to carry for the visit
  - Provide transport options and cost estimates
  - Store referral in session history
"""

from typing import Any, Optional
from langchain_core.messages import SystemMessage, HumanMessage

from agents.llm_factory import get_llm
from tools.healthcare_tools import generate_referral_summary, log_navigation_step
from utils.logger import app_logger, audit_logger


SYSTEM_PROMPT = """You are a Patient Care Navigation Coordinator for rural healthcare services in India.

Your role is to create clear, actionable referral and visit plans for patients who have been matched to a healthcare facility.

WHEN CREATING A REFERRAL PLAN:
1. Provide a numbered, step-by-step action plan
2. List documents the patient should carry:
   - Aadhaar card (for government schemes)
   - Health card (Ayushman Bharat / PMJAY / State scheme)
   - Previous medical records if any
   - Referral summary (generated by this system)
3. Mention government schemes the patient may be eligible for:
   - Ayushman Bharat - PMJAY (PM Jan Arogya Yojana)
   - State-specific health schemes
   - NHM (National Health Mission) services
4. Estimate travel time/distance if data is available
5. Provide the facility contact number for advance confirmation

LANGUAGE:
- Use simple, clear language
- Avoid medical jargon
- Be encouraging and supportive
- Remind the patient this is NAVIGATION GUIDANCE only

DISCLAIMER TO ALWAYS INCLUDE:
"⚠️ This navigation plan is an AI-generated support document. It does NOT replace a clinical referral issued by a qualified doctor. The receiving facility will conduct their own assessment."
"""


class ReferralPlanningAgent:
    """
    Agent 3: Referral Planning Agent

    State maintained:
        - referral_id
        - referral_summary_text
        - action_plan (list of steps)
        - documents_checklist
        - plan_generated
    """

    def __init__(self, session_id: str):
        self.session_id = session_id
        self.agent_name = "ReferralPlanningAgent"
        self.llm = get_llm(temperature=0.3)

        self.state: dict[str, Any] = {
            "referral_id": None,
            "referral_summary_text": None,
            "action_plan": [],
            "documents_checklist": [],
            "plan_generated": False,
        }

    def run(
        self,
        patient_context: str,
        district: str,
        state_name: str,
        target_facility: dict,
        target_department: str,
        urgency_level: str,
        chief_complaint: str,
        step_number: int = 3,
    ) -> dict[str, Any]:
        """
        Generate referral navigation plan for the patient.

        Args:
            patient_context: Summary from assessment agent (no PII)
            district: Patient's district
            state_name: Patient's state
            target_facility: Facility dict from discovery agent
            target_department: Recommended department
            urgency_level: Assessed urgency level
            chief_complaint: Category of complaint (not detailed symptoms)
            step_number: Navigation history step number

        Returns:
            dict with referral_id, referral_summary, action_plan, response_text
        """
        import time
        start_time = time.time()

        facility_name = target_facility.get("name", "Selected Facility")
        facility_phone = target_facility.get("phone", "N/A")
        facility_address = target_facility.get("address", "")
        facility_distance = target_facility.get("distance_km", "N/A")
        is_government = target_facility.get("is_government", True)

        # ── Tool Call: Generate referral summary ────────────────────────
        referral_result = generate_referral_summary(
            patient_context=f"Location: {district}, {state_name}. Need: {chief_complaint}. Urgency: {urgency_level}",
            referring_facility="AI Navigation System (Rural Healthcare Access)",
            target_facility=facility_name,
            target_department=target_department,
            urgency_level=urgency_level,
            reason_for_referral=f"Patient navigation for: {chief_complaint}",
            session_id=self.session_id,
        )

        self.state["referral_id"] = referral_result.get("referral_id")
        self.state["referral_summary_text"] = referral_result.get("referral_summary")

        # ── Build LLM prompt ─────────────────────────────────────────────
        govt_schemes = (
            "\n- Ayushman Bharat PMJAY: Free treatment up to ₹5 lakh/year for eligible families"
            "\n- NHM Free Diagnostics Scheme: Free lab tests at government facilities"
            "\n- National Free Medicines Initiative: Free essential medicines at PHC/CHC"
        ) if is_government else "\n- Private facility: Check for insurance coverage or government scheme tie-ups"

        prompt = f"""Create a detailed navigation plan for:

PATIENT DETAILS:
- Location: {district}, {state_name}
- Healthcare Need: {chief_complaint}
- Urgency Level: {urgency_level.upper()}

TARGET FACILITY:
- Name: {facility_name}
- Department: {target_department}
- Address: {facility_address}
- Distance: {facility_distance} km
- Phone: {facility_phone}
- Government Facility: {'Yes' if is_government else 'No'}
- Referral ID: {self.state['referral_id']}

APPLICABLE GOVERNMENT SCHEMES:{govt_schemes}

Please create:
1. A numbered step-by-step action plan (what to do right now)
2. A documents checklist (what to carry)
3. Important things to tell the doctor at arrival
4. Transport guidance
5. What to expect at the facility
6. Follow-up instructions"""

        messages = [
            SystemMessage(content=SYSTEM_PROMPT),
            HumanMessage(content=prompt),
        ]

        try:
            response = self.llm.invoke(messages)
            plan_text = response.content if hasattr(response, "content") else str(response)
        except Exception as e:
            app_logger.error(f"LLM error in ReferralPlanningAgent: {e}")
            plan_text = self._fallback_plan(facility_name, facility_phone, urgency_level)

        self.state["plan_generated"] = True
        self.state["action_plan"] = [plan_text]

        # ── Tool Call: Log navigation step ───────────────────────────────
        log_navigation_step(
            session_id=self.session_id,
            step_number=step_number,
            agent_name=self.agent_name,
            action_taken=f"Referral plan generated for {facility_name}",
            result_summary=f"Referral {self.state['referral_id']} created. Urgency: {urgency_level}",
            facilities_considered=[facility_name],
            recommended_facility_id=target_facility.get("id"),
            confidence_score=0.85 if target_facility.get("rating", 0) > 3 else 0.70,
            decision_factors=[
                f"Facility type: {target_facility.get('type', 'N/A')}",
                f"Government facility: {is_government}",
                f"Distance: {facility_distance} km",
                f"Department available: {target_department}",
            ],
            sources_used=["facility_database", "navigation_ai"],
        )

        # ── Audit logging ────────────────────────────────────────────────
        duration_ms = (time.time() - start_time) * 1000
        audit_logger.log(
            session_id=self.session_id,
            action_type="agent_call",
            agent_name=self.agent_name,
            action=f"generate_referral_plan → {facility_name}",
            outcome="success",
            metadata={
                "referral_id": self.state["referral_id"],
                "facility": facility_name,
                "urgency": urgency_level,
            },
            duration_ms=duration_ms,
        )

        return {
            "agent": self.agent_name,
            "referral_id": self.state["referral_id"],
            "referral_summary": self.state["referral_summary_text"],
            "navigation_plan": plan_text,
            "facility_name": facility_name,
            "facility_phone": facility_phone,
            "urgency_level": urgency_level,
            "plan_generated": True,
            "disclaimer": (
                "⚠️ This navigation plan is AI-generated guidance only. "
                "It does NOT replace a formal clinical referral from a qualified healthcare professional."
            ),
        }

    def _fallback_plan(self, facility_name: str, phone: str, urgency: str) -> str:
        """Fallback plan if LLM is unavailable."""
        if urgency == "emergency":
            return (
                f"🚨 EMERGENCY: Call 108 (ambulance) immediately!\n\n"
                f"If safe to travel: Go directly to {facility_name}.\n"
                f"Phone: {phone}\n\nCarry: Aadhaar card, any previous medical records."
            )
        return (
            f"**Step 1**: Call {facility_name} at {phone} to confirm availability.\n"
            f"**Step 2**: Carry your Aadhaar card and Ayushman Bharat health card.\n"
            f"**Step 3**: Bring any previous medical records.\n"
            f"**Step 4**: Visit the OPD (outpatient department) and show this referral summary.\n\n"
            f"For assistance: Call National Health Helpline 104 (free, 24×7)."
        )

    def get_state(self) -> dict[str, Any]:
        return self.state.copy()
